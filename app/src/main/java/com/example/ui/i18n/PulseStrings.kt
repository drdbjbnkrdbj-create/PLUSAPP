fun shortDayName(dayNumber: Int, lang: AppLanguage): String {
    val dow = DayOfWeek.of(dayNumber.coerceIn(1, 7))
    return when (lang) {
        AppLanguage.AR -> when (dow) {
            DayOfWeek.SATURDAY -> "السبت"
            DayOfWeek.SUNDAY -> "الأحد"
            DayOfWeek.MONDAY -> "الاثنين"
            DayOfWeek.TUESDAY -> "الثلاثاء"
            DayOfWeek.WEDNESDAY -> "الأربعاء"
            DayOfWeek.THURSDAY -> "الخميس"
            DayOfWeek.FRIDAY -> "الجمعة"
        }
        AppLanguage.EN -> when (dow) {
            DayOfWeek.SATURDAY -> "Sat"
            DayOfWeek.SUNDAY -> "Sun"
            DayOfWeek.MONDAY -> "Mon"
            DayOfWeek.TUESDAY -> "Tue"
            DayOfWeek.WEDNESDAY -> "Wed"
            DayOfWeek.THURSDAY -> "Thu"
            DayOfWeek.FRIDAY -> "Fri"
        }
    }
}

fun formatLocalizedDate(date: LocalDate, lang: AppLanguage): String {
    val locale = if (lang == AppLanguage.AR) Locale.forLanguageTag("ar") else Locale.ENGLISH
    val pattern = if (lang == AppLanguage.AR) "EEEE، d MMMM yyyy" else "EEEE, MMM d, yyyy"
    return date.format(DateTimeFormatter.ofPattern(pattern, locale))
}

fun formatLocalizedMonth(yearMonth: YearMonth, lang: AppLanguage): String {
    val locale = if (lang == AppLanguage.AR) Locale.forLanguageTag("ar") else Locale.ENGLISH
    return yearMonth.atDay(1).format(DateTimeFormatter.ofPattern("MMMM yyyy", locale))
}

fun formatLocalizedShortDate(date: LocalDate, lang: AppLanguage): String {
    val locale = if (lang == AppLanguage.AR) Locale.forLanguageTag("ar") else Locale.ENGLISH
    return date.format(DateTimeFormatter.ofPattern("d MMM", locale))
}

